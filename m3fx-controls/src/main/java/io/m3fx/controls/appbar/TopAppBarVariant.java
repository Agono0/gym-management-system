package io.m3fx.controls.appbar;

/** M3 top app bar variants. */
public enum TopAppBarVariant {
    /** Small (single row, 64dp). */
    SMALL,
    /** Center-aligned (single row, centered title). */
    CENTER_ALIGNED,
    /** Medium (two rows, 112dp, smaller headline on scroll). */
    MEDIUM,
    /** Large (two rows, 152dp, large headline). */
    LARGE
}
