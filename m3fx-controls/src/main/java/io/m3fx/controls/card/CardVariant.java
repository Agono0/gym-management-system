package io.m3fx.controls.card;

/**
 * M3 card variants.
 *
 * <p>See <a href="https://m3.material.io/components/cards/overview">M3 cards</a>.
 */
public enum CardVariant {
    /** Elevated card (level 1, surface container low). */
    ELEVATED,
    /** Filled card (surface container highest, no border). */
    FILLED,
    /** Outlined card (surface, outline-variant border). */
    OUTLINED
}
