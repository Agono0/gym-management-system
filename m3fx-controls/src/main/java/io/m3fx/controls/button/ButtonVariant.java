package io.m3fx.controls.button;

/**
 * M3 button variants.
 *
 * <p>See <a href="https://m3.material.io/components/buttons/overview">M3 buttons spec</a>.
 */
public enum ButtonVariant {
    /** Filled button (highest emphasis). */
    FILLED,
    /** Filled tonal button (medium emphasis). */
    TONAL,
    /** Outlined button (medium emphasis). */
    OUTLINED,
    /** Elevated button (medium emphasis, shadow). */
    ELEVATED,
    /** Text button (lowest emphasis). */
    TEXT,
    /** Liquid glass button (optical translucency, specular rim border). Styles in glass.css. */
    GLASS,
    /** Prominent liquid glass button (vibrant primary-container tint, stronger specular shadow). */
    GLASS_PROMINENT
}
