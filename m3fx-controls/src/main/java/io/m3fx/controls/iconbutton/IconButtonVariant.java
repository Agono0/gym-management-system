package io.m3fx.controls.iconbutton;

/**
 * M3 icon button variants.
 *
 * <p>See <a href="https://m3.material.io/components/icon-buttons/overview">M3 icon buttons</a>.
 */
public enum IconButtonVariant {
    /** Standard (no container). */
    STANDARD,
    /** Filled container. */
    FILLED,
    /** Filled tonal container. */
    TONAL,
    /** Outlined container. */
    OUTLINED
}
