package io.m3fx.controls.chip;

/**
 * M3 chip variants.
 *
 * <p>See <a href="https://m3.material.io/components/chips/overview">M3 chips</a>.
 */
public enum ChipVariant {
    /** Assist chip (elevated, icon + label, performs an action). */
    ASSIST,
    /** Filter chip (selectable, checkmark when selected). */
    FILTER,
    /** Input chip (avatar + label + close icon). */
    INPUT,
    /** Suggestion chip (outlined, low emphasis). */
    SUGGESTION
}
